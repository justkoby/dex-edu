// Generates src/data/nlMap.ts: the European Netherlands outline (Natural Earth via world-atlas 10m) + neighbours,
// Mercator-projected, with VERIFIED city coordinates. Run: node scripts/gen-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-10m.json", "utf8"));
const all = feature(topo, topo.objects.countries).features;
const nl = all.find((f) => f.properties.name === "Netherlands");
// keep only the European polygons (drop Bonaire, Saba, St Eustatius)
nl.geometry = { type: "MultiPolygon", coordinates: nl.geometry.coordinates.filter((poly) => poly[0][0][0] > 0) };
const W = 600, H = 700;
const proj = geoMercator().fitExtent([[30, 30], [W - 30, H - 30]], nl);
const path = geoPath(proj).digits(1);
const neighbours = all.filter((f) => ["Germany", "Belgium"].includes(f.properties.name)).map((f) => path(f));
// lon, lat — Haarlem 52.3874 N 4.6462 E (SRH Haarlem); Apeldoorn 52.2112 N 5.9699 E (Wittenborg main campus); Amsterdam 52.3676 N 4.9041 E
const cities = { haarlem: [4.6462, 52.3874], apeldoorn: [5.9699, 52.2112], amsterdam: [4.9041, 52.3676] };
const xy = Object.fromEntries(Object.entries(cities).map(([k, c]) => [k, proj(c).map((v) => +v.toFixed(1))]));
writeFileSync("src/data/nlMap.ts", `// GENERATED by scripts/gen-map.mjs — do not edit by hand.
export const NL_W = ${W};
export const NL_H = ${H};
export const NL_D = ${JSON.stringify(path(nl))};
export const NEIGHBOURS_D: string[] = ${JSON.stringify(neighbours)};
export const CITY: Record<"haarlem" | "apeldoorn" | "amsterdam", [number, number]> = ${JSON.stringify(xy)};
`);
console.log("map written", xy, path(nl).length, "chars");
