// Extracts the ORIGINAL paths of Logo.svg (unmodified) into src/motion/logoData.ts so each component can be animated.
// Logo.svg itself has no background rectangle: it is 8 orange mark paths + 30 navy wordmark paths on a transparent canvas.
import { readFileSync, writeFileSync } from "node:fs";
const s = readFileSync("Logo.svg", "utf8");
const vb = s.match(/viewBox="([^"]+)"/)[1].split(/\s+/).map(Number);
const paths = [...s.matchAll(/<path class="(cls-\d)" d="([^"]+)"/g)].map((m) => ({ fill: m[1] === "cls-2" ? "orange" : "navy", d: m[2] }));
writeFileSync("src/motion/logoData.ts", `// GENERATED by scripts/gen-logo.mjs from Logo.svg — do not edit.\nexport const LOGO_VIEWBOX = ${JSON.stringify(vb)} as const;\nexport const LOGO_PATHS: { fill: "orange" | "navy"; d: string }[] = ${JSON.stringify(paths)};\n`);
console.log(paths.length, "paths", vb);
