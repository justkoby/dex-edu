// Generates src/motion/mapData.ts: simplified Natural Earth (world-atlas 50m) paths for West Africa -> Central Europe,
// projected with Mercator from VERIFIED coordinates. Run: node scripts/gen-map.mjs   (devDeps: d3-geo, topojson-client, world-atlas)
import { readFileSync, writeFileSync } from "node:fs";
import { geoMercator, geoPath, geoInterpolate, geoDistance, geoGraticule10, geoBounds } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topo, topo.objects.countries).features;

// Verified coordinates (lon, lat): Accra, Ghana 5.6037 N, 0.1870 W; Budapest, Hungary 47.4979 N, 19.0402 E
const ACCRA = [-0.187, 5.6037];
const BUDAPEST = [19.0402, 47.4979];
const W = 2400, H = 3000;
const proj = geoMercator().fitExtent([[0, 0], [W, H]], { type: "MultiPoint", coordinates: [[-24, -6], [38, 58], [-24, 58], [38, -6]] });
const path = geoPath(proj).digits(1);

const inView = (f) => { const [[x0, y0], [x1, y1]] = geoBounds(f); return x1 > -30 && x0 < 45 && y1 > -12 && y0 < 64 && x1 - x0 < 300; };
const land = {};
for (const f of countries) if (inView(f)) { const d = path(f); if (d) land[f.id + ":" + (f.properties?.name ?? "")] = d; }

const interp = geoInterpolate(ACCRA, BUDAPEST);
const pts = Array.from({ length: 121 }, (_, i) => proj(interp(i / 120)));
const route = "M" + pts.map((p) => p[0].toFixed(1) + " " + p[1].toFixed(1)).join(" L");
const km = Math.round((geoDistance(ACCRA, BUDAPEST) * 6371) / 10) * 10;
const grat = path(geoGraticule10());
// geographic reference labels (lon, lat) — real places, projected with the same Mercator
const refs = [["ATLANTIC OCEAN", -15, 13], ["SAHARA", 12, 23.5], ["MEDITERRANEAN SEA", 17.5, 35.4], ["GULF OF GUINEA", 3.5, 2.6], ["BLACK SEA", 34, 43.4], ["ADRIATIC", 15.6, 43.4]];
const labels = refs.map(([t, lo, la]) => ({ t, x: +proj([lo, la])[0].toFixed(1), y: +proj([lo, la])[1].toFixed(1) }));

const out = `// GENERATED by scripts/gen-map.mjs — do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const ACCRA_XY: [number, number] = [${proj(ACCRA).map((v) => v.toFixed(1))}];
export const BUDAPEST_XY: [number, number] = [${proj(BUDAPEST).map((v) => v.toFixed(1))}];
export const GREAT_CIRCLE_KM = ${km};
export const ROUTE_D = ${JSON.stringify(route)};
export const GRATICULE_D = ${JSON.stringify(grat)};
export const REGION_LABELS: { t: string; x: number; y: number }[] = ${JSON.stringify(labels)};
export const COUNTRIES: Record<string, string> = ${JSON.stringify(land)};
`;
writeFileSync("src/motion/mapData.ts", out);
console.log("countries", Object.keys(land).length, "bytes", out.length, "km", km, proj(ACCRA), proj(BUDAPEST));
